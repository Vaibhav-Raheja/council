#!/usr/bin/env bash
# Guided setup. Idempotent — safe to re-run at any time.
set -uo pipefail

COUNCIL_HOME="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
export COUNCIL_HOME
. "$COUNCIL_HOME/lib/common.sh"
. "$COUNCIL_HOME/lib/registry.sh"
. "$COUNCIL_HOME/lib/policy.sh"

STEP=0
step() { STEP=$(( STEP + 1 )); echo; echo "── $STEP. $* ──"; }

ask_yes() {
  # Never auto-install when running non-interactively.
  [ -t 0 ] || return 1
  printf '   %s [y/N] ' "$1"
  read -r a
  case "$a" in [yY]*) return 0 ;; *) return 1 ;; esac
}

# Print an integration file with @COUNCIL_HOME@ replaced by this checkout's
# path. Parameter expansion, not sed, so no character in the path needs escaping.
render_integration() {
  local content
  content="$(cat "$1")" || return 1
  # The replacement is quoted: under bash 5.2's patsub_replacement an unquoted
  # & in it would expand to the matched text.
  printf '%s\n' "${content//@COUNCIL_HOME@/"$COUNCIL_HOME"}"
}

# Render into <dest> via a temp file, so a failed render never truncates an
# installed skill.
install_integration() {
  local tmp
  tmp="$(mktemp "$2.XXXXXX")" || return 1
  if render_integration "$1" > "$tmp"; then mv "$tmp" "$2"; else rm -f "$tmp"; return 1; fi
}

# Value of the environment variable NAMED by $1, or empty. The name comes from
# a provider .conf, so it is validated before the indirect lookup.
env_value() {
  council_is_ident "$1" || return 0
  printf '%s' "${!1:-}"
}

echo "council setup — $(council_os)"
echo "home: $COUNCIL_HOME"

# ---------------------------------------------------------------- 1. providers
step "Providers"
MISSING=""
for id in $(council_provider_ids); do
  if bin="$(council_provider_bin "$id" 2>/dev/null)"; then
    printf '   %-10s installed   %s\n' "$id" "$bin"
  else
    printf '   %-10s MISSING\n' "$id"
    MISSING="$MISSING $id"
    hint="$(council_provider_meta "$id" PROVIDER_INSTALL_HINT)"
    [ -n "$hint" ] && echo "              install: $hint"
  fi
done

if [ -n "$MISSING" ]; then
  echo
  echo "   Missing providers are simply skipped — council works with whatever"
  echo "   is present, as long as the policy invariants can still be met."
  for id in $MISSING; do
    cmd="$(council_provider_meta "$id" PROVIDER_INSTALL_CMD)"
    [ -n "$cmd" ] || continue
    if ask_yes "Install $id now?  ($cmd)"; then
      sh -c "$cmd" || council_warn "install of $id failed; continuing"
    fi
  done
fi

# --------------------------------------------------------------------- 2. auth
step "Sign in"
cat <<'EOS'
   OAuth is the default and needs no secrets on disk. Each CLI keeps its own
   token. These are interactive browser flows, so a headless call can never
   complete one — if a provider fails the live check below, sign in first.
EOS
echo
for id in $(council_provider_ids); do
  council_provider_available "$id" || continue
  hint="$(council_provider_meta "$id" PROVIDER_AUTH_HINT)"
  [ -n "$hint" ] && printf '   %-10s %s\n' "$id" "$hint"
done

cat <<'EOS'

   API keys are OPTIONAL. Nothing here requires one. If a provider you add
   supports a key, set its env var in your shell profile and that provider
   will use it; providers that use OAuth ignore keys entirely.
EOS
for id in $(council_provider_ids); do
  keyenv="$(council_provider_meta "$id" PROVIDER_API_KEY_ENV)"
  [ -n "$keyenv" ] || continue
  if [ -n "$(env_value "$keyenv")" ]; then
    printf '   %-10s %s is set\n' "$id" "$keyenv"
  else
    printf '   %-10s %s is unset (optional)\n' "$id" "$keyenv"
  fi
done

# --------------------------------------------------------------------- 3. PATH
step "Put council on PATH"
BINDIR="${COUNCIL_BINDIR:-$HOME/.local/bin}"
mkdir -p "$BINDIR"
# A plain copy would detach the script from lib/ and providers/, and on Windows
# `ln -s` silently produces a copy. So write a shim that pins COUNCIL_HOME and
# execs the real script — correct on every platform, symlinks or not.
# Replace only what an earlier install made: a symlink or a generated shim. An
# unrelated program that happens to be called council is left alone.
ours_launcher() {
  local t
  if [ -L "$1" ]; then
    t="$(readlink "$1")"
    case "$t" in */council) [ -f "${t%/council}/lib/common.sh" ] ;; *) return 1 ;; esac
  else
    grep -q 'Generated by council install.sh' "$1" 2>/dev/null
  fi
}
if [ -e "$BINDIR/council" ] || [ -L "$BINDIR/council" ]; then
  if ours_launcher "$BINDIR/council"; then
    rm -f "$BINDIR/council"
  else
    council_die "$BINDIR/council exists and was not installed by council; move it or set COUNCIL_BINDIR"
  fi
fi
if ln -s "$COUNCIL_HOME/council" "$BINDIR/council" 2>/dev/null && [ -L "$BINDIR/council" ]; then
  echo "   linked $BINDIR/council -> $COUNCIL_HOME/council"
else
  rm -f "$BINDIR/council"
  if {
    echo '#!/usr/bin/env bash'
    echo '# Generated by council install.sh — pins COUNCIL_HOME to the checkout.'
    # %q quotes the path for bash, so spaces, quotes or $ in it stay literal.
    printf 'COUNCIL_HOME=%q\n' "$COUNCIL_HOME"
    echo 'export COUNCIL_HOME'
    # shellcheck disable=SC2016  # written literally; expands when the launcher runs
    echo 'exec "$COUNCIL_HOME/council" "$@"'
  } > "$BINDIR/council" && chmod +x "$BINDIR/council"; then
    echo "   wrote launcher $BINDIR/council -> $COUNCIL_HOME (symlinks unavailable)"
  else
    council_warn "could not install into $BINDIR"
    INSTALL_RC=1
  fi
fi
case ":$PATH:" in
  *":$BINDIR:"*) echo "   $BINDIR is already on PATH" ;;
  *) echo "   NOTE: $BINDIR is not on PATH. Add this to your shell profile:"
     echo "         export PATH=\"$BINDIR:\$PATH\"" ;;
esac

# ------------------------------------------------------------- 4. time limits
step "Call time limits"
if tmo="$(council_timeout_cmd)" && [ -n "$tmo" ]; then
  echo "   model calls are capped via $tmo (COUNCIL_CALL_TIMEOUT, default 240s)"
else
  echo "   no timeout(1)/gtimeout found; calls are capped by council's built-in"
  echo "   watchdog instead (COUNCIL_CALL_TIMEOUT, default 240s)."
  if [ "$(council_os)" = macos ]; then
    echo "   Optional: 'brew install coreutils' provides gtimeout, which council"
    echo "   prefers when present. Nothing else needs it."
  fi
fi

# ------------------------------------------------------------------ 5. policy
step "Policy check"
echo "   rules: $(council_rules_file)"
printf '   reserved judge: %s\n' "$(council_policy_reserved_judge 2>/dev/null || echo none)"
# Held out exactly as 'council ask' holds them out: the reserved judge AND every
# final reviewer, so this preview names the panel a real round would convene.
RESERVED="$(council_policy_reserved 2>/dev/null | tr '\n' ' ' | sed 's/ *$//')"
printf '   held off the panel: %s\n' "${RESERVED:-none}"
# shellcheck disable=SC2086  # RESERVED is a list of ids, split on purpose
if panel="$(council_policy_panel advise "" $RESERVED 2>&1)"; then
  echo "   advisory panel: $(echo "$panel" | tr '\n' ' ')"
else
  echo "   PANEL UNSATISFIED:"
  printf '%s\n' "$panel" | while IFS= read -r line; do echo "     $line"; done
  echo "     Install another provider, or lower min-advisors in policy/rules.conf."
fi

# ------------------------------------------------------- 6. agent integration
step "Assistant integration (optional)"
INTEG="$COUNCIL_HOME/integrations/claude-code"
CLAUDE_DIR="${CLAUDE_CONFIG_DIR:-$HOME/.claude}"
if [ -d "$INTEG" ] && [ -d "$CLAUDE_DIR" ]; then
  echo "   Claude Code detected at $CLAUDE_DIR."
  echo "   This wires the council to convene ITSELF, so you never type 'council'."
  # Both files carry @COUNCIL_HOME@; render_integration fills in this checkout.
  if [ -f "$CLAUDE_DIR/skills/council/SKILL.md" ]; then
    echo "   skill already installed — refreshing it"
    mkdir -p "$CLAUDE_DIR/skills/council"
    install_integration "$INTEG/SKILL.md" "$CLAUDE_DIR/skills/council/SKILL.md" ||
      { council_warn "could not refresh the skill"; INSTALL_RC=1; }
  elif ask_yes "Install the auto-invoke skill into $CLAUDE_DIR/skills/council?"; then
    mkdir -p "$CLAUDE_DIR/skills/council"
    install_integration "$INTEG/SKILL.md" "$CLAUDE_DIR/skills/council/SKILL.md" &&
      echo "   installed the skill"
  fi
  if grep -q "^# Multi-model council" "$CLAUDE_DIR/CLAUDE.md" 2>/dev/null; then
    echo "   CLAUDE.md already carries the council rules — leaving it alone"
  elif ask_yes "Append the routing rules to $CLAUDE_DIR/CLAUDE.md?"; then
    printf '\n' >> "$CLAUDE_DIR/CLAUDE.md"
    render_integration "$INTEG/CLAUDE.md.snippet" >> "$CLAUDE_DIR/CLAUDE.md" &&
      echo "   appended the rules"
  fi
else
  echo "   Claude Code not detected — skipping."
  echo "   See integrations/claude-code/README.md to wire another assistant."
fi

# ------------------------------------------------------------------ 7. verify
step "Live check"
"$COUNCIL_HOME/council" doctor | sed -n '/live check/,$p' | sed 's/^/   /'
DOCTOR_RC="${PIPESTATUS[0]}"
if [ "$DOCTOR_RC" -ne 0 ]; then
  echo
  echo "   Live check FAILED for at least one installed provider, or the panel"
  echo "   cannot be formed. Sign in where it says FAILED, then: council doctor"
fi

cat <<'EOS'

Setup complete. Next:

   council roles                 who is good at what
   council providers             capabilities and availability
   council ask "<question>"      convene the panel
   council review <file>         code review by the panel

Adding another LLM:
   cp providers/_template.conf providers/<yourmodel>.conf   and edit it.
   No engine changes are needed — routing follows the capabilities you declare.
EOS

[ "$DOCTOR_RC" -ne 0 ] && exit "$DOCTOR_RC"
exit "${INSTALL_RC:-0}"
